import json
import sys
from pathlib import Path
from urllib.parse import parse_qs, urlparse

import pytest

sys.path.insert(0, str(Path(__file__).parent))
import vpnctl


def test_build_link_golden():
    link = vpnctl.build_link(
        host="203.0.113.7",
        port=443,
        user_id="5bab9cc8-b064-4b53-81c8-117be55d2238",
        sni="www.apple.com",
        pbk="dQwL5f6_xBW0mTs6UUPAObrxh-Q0sXzd_2jQCdZsdTI",
        sid="0123456789abcdef",
        remark="my vpn",
    )
    assert link == (
        "vless://5bab9cc8-b064-4b53-81c8-117be55d2238@203.0.113.7:443"
        "?encryption=none&security=reality&sni=www.apple.com&fp=chrome"
        "&pbk=dQwL5f6_xBW0mTs6UUPAObrxh-Q0sXzd_2jQCdZsdTI"
        "&sid=0123456789abcdef&spx=%2F&type=tcp&headerType=none#my%20vpn"
    )


def test_keys_round_trip():
    priv, pub = vpnctl.generate_keys()
    assert len(vpnctl.b64url_decode(priv)) == 32
    assert vpnctl.public_from_private(priv) == pub


def test_public_from_private_matches_go_keygen():
    # generated by core/cmd/keygen
    priv = "mvJdyjgOLnq04SVVE59VAREIgTD0PuvhbHpu--JrVnU"
    pub = "dQwL5f6_xBW0mTs6UUPAObrxh-Q0sXzd_2jQCdZsdTI"
    assert vpnctl.public_from_private(priv) == pub


def run_cli(*argv):
    vpnctl.main(list(argv))


def test_init_and_links(tmp_path, capsys):
    out = tmp_path / "server.json"
    run_cli(
        "init",
        "--host", "198.51.100.9",
        "--port", "8443",
        "--listen", "127.0.0.1:8443",
        "--dest", "www.apple.com:443",
        "--sni", "www.apple.com",
        "--out", str(out),
        "--uuid", "5bab9cc8-b064-4b53-81c8-117be55d2238",
        "--short-id", "0123456789abcdef",
        "--name", "macbook",
    )
    cfg = json.loads(out.read_text())
    assert cfg["listen"] == "127.0.0.1:8443"
    assert cfg["users"][0]["id"] == "5bab9cc8-b064-4b53-81c8-117be55d2238"
    reality = cfg["reality"]
    assert reality["dest"] == "www.apple.com:443"
    assert reality["server_names"] == ["www.apple.com"]
    assert reality["short_ids"] == ["0123456789abcdef"]
    assert len(vpnctl.b64url_decode(reality["private_key"])) == 32

    link = capsys.readouterr().out.strip().splitlines()[-1]
    parsed = urlparse(link)
    assert parsed.scheme == "vless"
    assert parsed.username == "5bab9cc8-b064-4b53-81c8-117be55d2238"
    assert parsed.hostname == "198.51.100.9"
    assert parsed.port == 8443
    q = parse_qs(parsed.query)
    assert q["security"] == ["reality"]
    assert q["sni"] == ["www.apple.com"]
    assert q["fp"] == ["chrome"]
    assert q["pbk"] == [vpnctl.public_from_private(reality["private_key"])]
    assert q["sid"] == ["0123456789abcdef"]
    assert q["spx"] == ["/"]
    assert q["type"] == ["tcp"]


def test_init_refuses_overwrite(tmp_path):
    out = tmp_path / "server.json"
    run_cli("init", "--host", "1.2.3.4", "--out", str(out))
    with pytest.raises(SystemExit):
        run_cli("init", "--host", "1.2.3.4", "--out", str(out))
    run_cli("init", "--host", "1.2.3.4", "--out", str(out), "--force")


def test_add_user(tmp_path, capsys):
    out = tmp_path / "server.json"
    run_cli("init", "--host", "1.2.3.4", "--out", str(out))
    capsys.readouterr()
    run_cli("add-user", "--config", str(out), "--host", "1.2.3.4", "--name", "phone")
    cfg = json.loads(out.read_text())
    assert len(cfg["users"]) == 2
    assert cfg["users"][1]["name"] == "phone"
    links = [line for line in capsys.readouterr().out.splitlines() if line.startswith("vless://")]
    assert len(links) == 2
